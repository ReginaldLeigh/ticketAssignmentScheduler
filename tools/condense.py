#!/usr/bin/env python3
"""Build a 3-file version of the app for quick testing: dist/Code.gs, dist/Index.html, dist/appsscript.json.

Each original file appears in Code.gs under a banner like  /* ═══ BigQuery.gs ═══ */  so the
NoTableCreation tests can still check which section talks to BigQuery or the Sheet.
Run:  python3 tools/condense.py      Test the result:  APP_SRC=dist npm test
"""
import os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, DIST = os.path.join(ROOT, 'src'), os.path.join(ROOT, 'dist')
ORDER = ['QueryConfig', 'Errors', 'BigQuery', 'Store', 'Config', 'Lease', 'SchemaCheck', 'Subject', 'Rules',
         'Balancer', 'FollowUp', 'Ivanti', 'Writeback', 'Vertex', 'Pipeline', 'Triggers', 'WebApp']

def read(*p):
    with open(os.path.join(SRC, *p), encoding='utf-8') as f:
        return f.read()

missing = set(f[:-3] for f in os.listdir(SRC) if f.endswith('.gs')) ^ set(ORDER)
assert not missing, 'ORDER is out of date: %s' % missing

header = """/**
 * Ticket Assignment Scheduler: single-file build for quick testing (generated by tools/condense.py).
 *
 * Files in this Apps Script project:  Code.gs (this file) · Index.html · appsscript.json
 * Start with the QueryConfig section right below: every developer setting is there.
 * This app NEVER creates tables or Sheet tabs. Create them first, by hand, from docs/SCHEMA.md.
 */
"""
parts = [header]
for name in ORDER:
    body = read(name + '.gs').strip() + '\n'
    if name == 'WebApp':
        body = body.replace(
            "return HtmlService.createTemplateFromFile('html/Index').evaluate()",
            "return HtmlService.createHtmlOutputFromFile('Index')")
        body = body.replace(
            "function include(name) { return HtmlService.createHtmlOutputFromFile(name).getContent(); }\n\n", "")
        assert "createTemplateFromFile" not in body and "function include" not in body
    bar = '═' * 30
    parts.append('\n/* %s %s.gs %s */\n\n%s' % (bar, name, bar, body))

os.makedirs(DIST, exist_ok=True)
for f in os.listdir(DIST):
    os.remove(os.path.join(DIST, f))
with open(os.path.join(DIST, 'Code.gs'), 'w', encoding='utf-8') as f:
    f.write(''.join(parts))

index = read('html', 'Index.html')
index = index.replace("<?!= include('html/Styles'); ?>", read('html', 'Styles.html').strip())
index = index.replace("<?!= include('html/App'); ?>", read('html', 'App.html').strip())
assert '<?' not in index, 'unresolved scriptlet in Index.html'
with open(os.path.join(DIST, 'Index.html'), 'w', encoding='utf-8') as f:
    f.write(index)
shutil.copy(os.path.join(SRC, 'appsscript.json'), os.path.join(DIST, 'appsscript.json'))
print('Built', ', '.join(sorted(os.listdir(DIST))))
